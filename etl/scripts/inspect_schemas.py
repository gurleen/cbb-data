"""Write the column list of one season of every upstream dataset to docs/schemas.md.

    uv run python scripts/inspect_schemas.py --season 2026 --write ../docs/schemas.md

Also reports which seasons exist per dataset (GitHub API listing; HEAD probes otherwise)
and column drift against an older season.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import duckdb

from cbb_etl.config import SPORT_CONFIG, Settings
from cbb_etl.extract import AssetNotFound, ReleaseClient
from cbb_etl.seasons import current_season

HEADER = """# Upstream schemas

Generated by `etl/scripts/inspect_schemas.py` (season {season}; drift column compares against
season {old}). Source: `https://github.com/sportsdataverse/sportsdataverse-data/releases`.
Only Parquet files are used.

{notes}
"""

NOTES = Path(__file__).with_name("schema_notes.md")


def seasons_for(client: ReleaseClient, sp, ds) -> list[int]:
    listed = client.available_seasons(sp, ds)
    if listed is not None:
        return listed
    out = []
    for s in range(2002, current_season() + 1):
        try:
            client.resolve(sp, ds, s)
            out.append(s)
        except AssetNotFound:
            pass
    return out


def fmt_ranges(seasons: list[int]) -> str:
    if not seasons:
        return "none"
    parts, start, prev = [], seasons[0], seasons[0]
    for s in seasons[1:] + [None]:
        if s is not None and s == prev + 1:
            prev = s
            continue
        parts.append(f"{start}" if start == prev else f"{start}-{prev}")
        if s is not None:
            start = prev = s
    return ", ".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--season", type=int, default=2026)
    ap.add_argument("--old-season", type=int, default=2016)
    ap.add_argument("--write", type=Path)
    args = ap.parse_args()
    settings = Settings.from_env()
    client = ReleaseClient(settings.cache_dir, settings.github_token)
    con = duckdb.connect()
    out = [
        HEADER.format(
            season=args.season,
            old=args.old_season,
            notes=NOTES.read_text() if NOTES.exists() else "",
        )
    ]

    for sp in SPORT_CONFIG.values():
        out.append(f"\n## {sp.code.upper()} (`{sp.tag_prefix}*`)\n")
        for ds in sp.datasets.values():
            seasons = seasons_for(client, sp, ds)
            out.append(f"\n### `{ds.key}`\n")
            out.append(
                f"* tag `{ds.tag(sp)}`, file `{ds.filename(sp, 0)[:-12]}{{season}}"
                f".parquet`\n* seasons: {fmt_ranges(seasons)}\n"
            )
            if args.season not in seasons:
                out.append(f"* (no {args.season} file)\n")
                continue
            path = client.fetch(client.resolve(sp, ds, args.season))
            cols = con.execute(f"DESCRIBE SELECT * FROM '{path}'").fetchall()
            (n,) = con.execute(f"SELECT count(*) FROM '{path}'").fetchone()
            drift = ""
            if args.old_season in seasons and ds.key not in ("pbp", "shots"):
                old = client.fetch(client.resolve(sp, ds, args.old_season))
                old_cols = {
                    r[0]: r[1] for r in con.execute(f"DESCRIBE SELECT * FROM '{old}'").fetchall()
                }
                new_cols = {r[0]: r[1] for r in cols}
                added = sorted(set(new_cols) - set(old_cols))
                removed = sorted(set(old_cols) - set(new_cols))
                retyped = sorted(
                    c for c in set(new_cols) & set(old_cols) if new_cols[c] != old_cols[c]
                )
                if added or removed or retyped:
                    drift = (
                        f"* drift vs {args.old_season}: added {added or '-'}; "
                        f"removed {removed or '-'}; retyped {retyped or '-'}\n"
                    )
            out.append(f"* {args.season}: {n:,} rows, {len(cols)} columns\n{drift}\n")
            out.append("| column | type |\n|---|---|\n")
            out += [f"| `{c[0]}` | {c[1]} |\n" for c in cols]

    text = "".join(out)
    if args.write:
        args.write.write_text(text)
        print(f"wrote {args.write}")
    else:
        print(text)


if __name__ == "__main__":
    main()
