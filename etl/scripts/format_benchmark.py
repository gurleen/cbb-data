"""Compare raw JSON vs gzip JSON vs MessagePack sizes for a sample of published objects.

uv run cbb-etl run --seasons 2026 --targets r2 --dry-run --out-dir out
uv run python scripts/format_benchmark.py out --write ../docs/format-benchmark.md
"""

from __future__ import annotations

import argparse
import gzip
import json
import random
import time
from pathlib import Path

import msgpack

from cbb_etl.encode import canonical_json


def sample_files(root: Path, per_season_teams: int = 5) -> list[Path]:
    out: list[Path] = []
    for sport_dir in sorted((root / "v1").glob("*")):
        if not sport_dir.is_dir():
            continue
        out += [p for p in [sport_dir / "seasons.json"] if p.exists()]
        for season_dir in sorted(p for p in sport_dir.iterdir() if p.is_dir()):
            out += [season_dir / "teams.json", season_dir / "team-stats.json"]
            teams = sorted((season_dir / "teams").glob("*.json"))
            teams = [t for t in teams if not t.name.endswith(".meta.json")]
            random.Random(0).shuffle(teams)
            out += teams[:per_season_teams]
    return [p for p in out if p.exists()]


def measure(obj) -> dict[str, int]:
    raw = canonical_json(obj)
    mp = msgpack.packb(obj, use_bin_type=True)
    return {
        "json": len(raw),
        "json_gzip": len(gzip.compress(raw, 9, mtime=0)),
        "msgpack": len(mp),
        "msgpack_gzip": len(gzip.compress(mp, 9, mtime=0)),
    }


def fmt(n: float) -> str:
    return f"{n / 1024:,.1f} KB" if n >= 1024 else f"{n:,.0f} B"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--write", type=Path, help="write markdown report here")
    args = ap.parse_args()

    groups: dict[str, list[dict[str, int]]] = {}
    for p in sample_files(args.out_dir):
        obj = json.loads(gzip.decompress(p.read_bytes()))
        kind = "teams/{id}.json" if p.parent.name == "teams" else p.name
        groups.setdefault(kind, []).append(measure(obj))

    # decode-speed comparison on the largest object type
    biggest = max(sample_files(args.out_dir), key=lambda p: p.stat().st_size)
    raw = gzip.decompress(biggest.read_bytes())
    obj = json.loads(raw)
    mp = msgpack.packb(obj, use_bin_type=True)
    gz = gzip.compress(raw, 9, mtime=0)
    t = time.perf_counter()
    for _ in range(50):
        json.loads(gzip.decompress(gz))
    t_json = (time.perf_counter() - t) / 50
    t = time.perf_counter()
    for _ in range(50):
        msgpack.unpackb(mp)
    t_mp = (time.perf_counter() - t) / 50

    lines = [
        "| object | n | raw JSON | gzip JSON | MessagePack | MessagePack + gzip | gzip ratio |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for kind, rows in sorted(groups.items()):
        avg = {k: sum(r[k] for r in rows) / len(rows) for k in rows[0]}
        lines.append(
            f"| `{kind}` | {len(rows)} | {fmt(avg['json'])} | {fmt(avg['json_gzip'])} | "
            f"{fmt(avg['msgpack'])} | {fmt(avg['msgpack_gzip'])} | "
            f"{avg['json'] / avg['json_gzip']:.1f}x |"
        )
    table = "\n".join(lines)
    print(table)
    print(
        f"\nlargest object {biggest.name}: python gzip+json decode {t_json * 1e3:.2f} ms, "
        f"msgpack decode {t_mp * 1e3:.2f} ms"
    )

    if args.write:
        args.write.write_text(
            REPORT.format(
                table=table,
                biggest=f"{biggest.parent.parent.name}/{biggest.parent.name}/{biggest.name}"
                if biggest.parent.name == "teams"
                else f"{biggest.parent.name}/{biggest.name}",
                t_json=f"{t_json * 1e3:.2f}",
                t_mp=f"{t_mp * 1e3:.2f}",
            )
        )
        print(f"wrote {args.write}")


REPORT = """# Format benchmark: JSON vs gzip JSON vs MessagePack

Generated by `etl/scripts/format_benchmark.py` from a `--dry-run` output (average size per
object, all sampled seasons; team files are a random sample of 5 per season).

{table}

Decode time for the largest sampled object (`{biggest}`), Python, mean of 50:
gzip + JSON {t_json} ms, MessagePack {t_mp} ms.

## Takeaways

* gzip shrinks the big list objects (`teams.json`, `team-stats.json`) about 6x. The
  ~1 KB per-team objects shrink about 2x.
* MessagePack alone saves little: under 1% on `team-stats.json` and about 20% on
  `teams.json`. Our payloads are mostly rounded floats, which JSON writes in 3-5 bytes
  (`101.8`) and MessagePack writes as 9-byte float64s.
* **MessagePack + gzip is larger than gzip JSON** (by 5-16% here), because the binary
  floats compress worse than short decimal strings.
* MessagePack decodes faster in Python. In the Worker, though, the stored gzip bytes go
  straight to the client, and browsers handle gzip and JSON natively, while MessagePack
  needs a client library.
* **Decision: keep gzip JSON.** The `Encoder` interface (`etl/src/cbb_etl/encode.py`)
  makes a later swap a one-line change.
"""


if __name__ == "__main__":
    main()
